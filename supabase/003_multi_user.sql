-- Each signed-in person hires their own Sara with their own settings,
-- jobs, run log and watchlist. Only invited emails can create an account.
--
-- Before running: sign in to the dashboard once as the owner
-- (anikshovan@gmail.com). Then: SQL Editor > New query > paste > Run.
-- =====================================================================

do $$
begin
  if not exists (select 1 from auth.users where lower(email) = 'anikshovan@gmail.com') then
    raise exception 'Sign in to the dashboard once as anikshovan@gmail.com, then run this migration again.';
  end if;
end $$;

-- The owner manages invites
create or replace function public.is_owner() returns boolean
language sql stable as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) = 'anikshovan@gmail.com'
$$;

-- ---------------------------------------------------------------------
-- 1. Every row belongs to a user. Existing rows belong to the owner.
-- ---------------------------------------------------------------------
alter table public.jobs      add column if not exists user_id uuid references auth.users(id) on delete cascade default auth.uid();
alter table public.runs      add column if not exists user_id uuid references auth.users(id) on delete cascade default auth.uid();
alter table public.companies add column if not exists user_id uuid references auth.users(id) on delete cascade default auth.uid();
alter table public.profile   add column if not exists user_id uuid references auth.users(id) on delete cascade default auth.uid();
alter table public.profile   add column if not exists display_name text;

update public.jobs      set user_id = (select id from auth.users where lower(email) = 'anikshovan@gmail.com') where user_id is null;
update public.runs      set user_id = (select id from auth.users where lower(email) = 'anikshovan@gmail.com') where user_id is null;
update public.companies set user_id = (select id from auth.users where lower(email) = 'anikshovan@gmail.com') where user_id is null;
update public.profile   set user_id = (select id from auth.users where lower(email) = 'anikshovan@gmail.com'),
                            display_name = coalesce(display_name, 'Bala')
  where user_id is null;

alter table public.jobs      alter column user_id set not null;
alter table public.runs      alter column user_id set not null;
alter table public.companies alter column user_id set not null;
alter table public.profile   alter column user_id set not null;

create index if not exists jobs_user_idx on public.jobs (user_id, found_at desc);
create index if not exists runs_user_idx on public.runs (user_id, started_at desc);

-- Uniqueness is now per user (two people can track the same job)
alter table public.jobs      drop constraint if exists jobs_url_key;
alter table public.jobs      drop constraint if exists jobs_source_external_id_key;
alter table public.companies drop constraint if exists companies_name_key;
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'jobs_user_url_key') then
    alter table public.jobs add constraint jobs_user_url_key unique (user_id, url);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'jobs_user_source_external_id_key') then
    alter table public.jobs add constraint jobs_user_source_external_id_key unique (user_id, source, external_id);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'companies_user_name_key') then
    alter table public.companies add constraint companies_user_name_key unique (user_id, name);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'profile_user_id_key') then
    alter table public.profile add constraint profile_user_id_key unique (user_id);
  end if;
end $$;

-- ---------------------------------------------------------------------
-- 2. One profile (one Sara) per user, instead of a single row
-- ---------------------------------------------------------------------
alter table public.profile drop constraint if exists profile_id_check;
do $$ begin
  if (select is_identity from information_schema.columns
      where table_schema = 'public' and table_name = 'profile' and column_name = 'id') = 'NO' then
    alter table public.profile alter column id drop default;
    alter table public.profile alter column id add generated by default as identity;
    perform setval(pg_get_serial_sequence('public.profile', 'id'), (select coalesce(max(id), 1) from public.profile));
  end if;
end $$;
alter table public.profile alter column role_families set default '[]'::jsonb;
alter table public.profile alter column locations     set default '{}'::jsonb;
alter table public.profile alter column exclusions    set default '{}'::jsonb;
alter table public.profile alter column seniority     set default '["mid", "senior", "lead"]'::jsonb;
alter table public.profile alter column min_monthly_usd set default 0;
alter table public.profile alter column run_time      set default '09:00';

-- ---------------------------------------------------------------------
-- 3. Security: each person sees and changes only their own rows
-- ---------------------------------------------------------------------
drop policy if exists "Owner full access" on public.jobs;
drop policy if exists "Owner full access" on public.runs;
drop policy if exists "Owner full access" on public.profile;
drop policy if exists "Owner full access" on public.companies;
drop policy if exists "Own rows" on public.jobs;
drop policy if exists "Own rows" on public.runs;
drop policy if exists "Own rows" on public.profile;
drop policy if exists "Own rows" on public.companies;

create policy "Own rows" on public.jobs      for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Own rows" on public.runs      for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Own rows" on public.profile   for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "Own rows" on public.companies for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

-- ---------------------------------------------------------------------
-- 4. Invite list: up to 5 emails, managed by the owner on the dashboard
-- ---------------------------------------------------------------------
create table if not exists public.invites (
  email      text primary key check (email = lower(email)),
  note       text,
  invited_at timestamptz not null default now()
);
alter table public.invites enable row level security;
drop policy if exists "Owner reads invites" on public.invites;
drop policy if exists "Owner adds invites" on public.invites;
drop policy if exists "Owner removes invites" on public.invites;
create policy "Owner reads invites"   on public.invites for select to authenticated using (public.is_owner());
create policy "Owner adds invites"    on public.invites for insert to authenticated
  with check (public.is_owner() and (select count(*) from public.invites) < 5);
create policy "Owner removes invites" on public.invites for delete to authenticated using (public.is_owner());

-- Only the owner and invited emails can create an account
create or replace function public.gate_signups() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if lower(new.email) = 'anikshovan@gmail.com'
     or exists (select 1 from public.invites where email = lower(new.email)) then
    return new;
  end if;
  raise exception 'SARA_NOT_INVITED: % is not on the invite list', new.email;
end $$;

drop trigger if exists gate_signups on auth.users;
create trigger gate_signups before insert on auth.users
  for each row execute function public.gate_signups();

